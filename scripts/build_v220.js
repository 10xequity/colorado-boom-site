const D = '2026-10-22';
const V = 'v2.20';
const PREV = 'v2.19';
function once(src, a, b, l) { const n = src.split(a).length - 1; if (n !== 1) throw new Error(l + ': anchor count ' + n); return src.replace(a, () => b); }
const load = f => { const raw = fs.readFileSync(R + f, 'utf8'); return { crlf: raw.includes('\r\n'), h: raw.replace(/\r\n/g, '\n') }; };
const save = (f, o) => fs.writeFileSync(R + f, o.crlf ? o.h.replace(/\n/g, '\r\n') : o.h);
const r = render({ img: 'assets/img/coaches/', live: true });
const o = load('coaching-staff.html'); let h = o.h;
if (!h.includes(`<!-- BUILD ${PREV} `)) throw new Error('expected a ' + PREV + ' page');
// style block
const sa = h.indexOf('  <style>\n'); const sb = h.indexOf('  </style>', sa);
if (sa < 0 || sb < sa) throw new Error('style block');
h = h.slice(0, sa) + '  <style>\n    /* [CO] trading-card staff page + Battle Arena. Generated by scratchpad gen_v7.js render({live:true}); edit there, not here. */' + r.CSS + '  </style>' + h.slice(sb + '  </style>'.length);
// body block: the generated section up to the footer
const ba = h.indexOf('  <!-- ===== [CO-01..CO-04]'); const bb = h.indexOf('  <!-- ============ [FT] FOOTER');
if (ba < 0 || bb < ba) throw new Error('body block');
h = h.slice(0, ba) + `  <!-- ===== [CO-01..CO-04] Coaching staff as trading cards + Battle Arena (${V}) ===== -->
<div id="tc">
${r.hero}
${r.bands}
<section class="band teal" style="padding-block:18px"><div class="wrap cta"><a class="btn" href="mailto:admin@coloradoboom.com">Interested in Coaching? Contact Us</a></div></section>
${r.dexHtml}
</div>
` + h.slice(bb);
// script block: the generated <script> right before main.js
const ma = h.indexOf('  <script src="assets/js/main.js"></script>'); if (ma < 0) throw new Error('main.js');
const sc = h.lastIndexOf('  <script>\n  (function(){', ma); if (sc < 0 || ma - sc > 200000) throw new Error('old script');
h = h.slice(0, sc) + r.SCRIPT.split('\n').map(l => '  ' + l).join('\n') + '\n' + h.slice(ma);
// sanity
const vis = h.replace(/<!--[\s\S]*?-->/g, '');
for (const id of REAL) if (!fs.existsSync(R + 'assets/img/coaches/cut/' + id + '.webp')) throw new Error('missing ' + id);
if (!fs.existsSync(R + 'assets/img/coaches/ryl-logo.webp')) throw new Error('missing ryl logo');
if (/boom-logo\.png|img\/cut\/|coloradoboom\.com\/teams\.html|Base Set|movebar/.test(vis)) throw new Error('leftover markup');
if ((vis.match(/<article class="card/g) || []).length !== ALLP.length) throw new Error('card count');
if ((vis.match(/<script>/g) || []).length !== 1) throw new Error('script count');
if (!vis.includes('id="pad"') || !vis.includes('id="koOv"') || !vis.includes('id="padAuto"') || !vis.includes('class="cb"') || !vis.includes('Super Dig')) throw new Error('round 9 markers');
h = h.replace(/(  <!-- BUILD v)/, `  <!-- BUILD ${V} · ${D} · [CO] Battle Arena round 9: outsides, right sides and setters carry a minor 1-cost shield (10) instead of a 2-cost swing; Street-Fighter K.O. splash then a centred Next Opponent overlay with the win streak; a scoring ball lands on the floor in 16-bit; pad has bigger labels, smaller buttons, an opaque backdrop and an Auto button; HUD bar shortened so 3-digit HP fits, card names shrink to fit, weakness text wraps; every card has a RYL card back (tap to flip, arena cards flip in); K.O. card no longer rotates (Chrome clipped it). Generated from scratchpad gen_v7.js. -->
$1`);
o.h = h; save('coaching-staff.html', o);
