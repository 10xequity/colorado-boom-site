// v2.51: rebuild coaching-staff.html from gen_v7.js. The generator now carries the v2.36/v2.37/v2.40 hand edits
// (Matthew Jeung, Kimberlyn Krise, Jamison's 480x540 photo), flip cards are role="button" with aria-pressed, the page
// script waits for the first interaction or for the arena to near the viewport, and the card back uses logo.webp.
// Safe to re-run: it replaces the generated style, body and script blocks in place.
const fs = require('fs');
const { render, ALLP, GUESTS } = require('./gen_v7.js');
const R = (process.argv[2] || require('path').join(__dirname, '..')).replace(/[\/\\]*$/, '/');
const load = f => { const raw = fs.readFileSync(R + f, 'utf8'); return { crlf: raw.includes('\r\n'), h: raw.replace(/\r\n/g, '\n') }; };
const save = (f, o) => fs.writeFileSync(R + f, o.crlf ? o.h.replace(/\n/g, '\r\n') : o.h);
const r = render({ img: 'assets/img/coaches/', live: true, av: '239' });
const o = load('coaching-staff.html'); let h = o.h;
const sa = h.indexOf('  <style>\n'); const sb = h.indexOf('  </style>', sa);
if (sa < 0 || sb < sa) throw new Error('style block');
h = h.slice(0, sa) + '  <style>\n    /* [CO] trading-card staff page + Battle Arena. Generated by scripts/gen_v7.js render({live:true}); edit there, not here. */' + r.CSS + '  </style>' + h.slice(sb + '  </style>'.length);
const ba = h.indexOf('  <!-- ===== [CO-01..CO-04]'); const bb = h.indexOf('  <!-- ============ [FT] FOOTER');
if (ba < 0 || bb < ba) throw new Error('body block');
h = h.slice(0, ba) + `  <!-- ===== [CO-01..CO-04] Coaching staff as trading cards + Battle Arena (v2.51) ===== -->
<div id="tc">
${r.hero}
${r.bands}
<section class="band teal" style="padding-block:18px"><div class="wrap cta"><a class="btn" href="mailto:admin@coloradoboom.com">Interested in Coaching? Contact Us</a></div></section>
${r.dexHtml}
</div>
` + h.slice(bb);
const ma = h.indexOf('  <script src="assets/js/main.js"></script>'); if (ma < 0) throw new Error('main.js');
const sc = h.lastIndexOf('  <script>\n  (function(){', ma); if (sc < 0 || ma - sc > 250000) throw new Error('old script');
h = h.slice(0, sc) + r.SCRIPT.split('\n').map(l => '  ' + l).join('\n') + '\n' + h.slice(ma);
const vis = h.replace(/<!--[\s\S]*?-->/g, '');
if ((vis.match(/<article class="card/g) || []).length !== ALLP.length + 1 + GUESTS.length) throw new Error('card count');
if ((vis.match(/<script>/g) || []).length !== 1) throw new Error('script count');
for (const m of ['Matthew Jeung', 'Kimberlyn Krise', '14 Colorado - Kimberlyn', 'height="540"', "setAttribute('aria-pressed'", 'deferred boot', 'assets/img/logo.webp']) if (!h.includes(m)) throw new Error('missing ' + m);
o.h = h; save('coaching-staff.html', o);
console.log('ok v2.51 cards', ALLP.length, 'html', h.length);
